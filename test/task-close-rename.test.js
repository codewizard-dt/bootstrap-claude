#!/usr/bin/env node
// Static enforcement of the hard rename of the old trash-named task skill to
// `task-close`. Zero-dependency: node:test + node:assert only, mirroring the
// sibling skill-content suites (test/archive-work-item.test.js,
// test/task-assess-rename.test.js).
//
// Run: npm test   (or: node --test test/task-close-rename.test.js)
//
// WHY THIS IS TESTED AT ALL. Skills are markdown-as-program: a stale reference
// to the old skill name in a sibling skill, a doc table, a test constant or a
// knowledge page is a silent runtime failure (an agent is told to invoke a
// skill that no longer exists). The rename therefore cannot be verified by
// running anything — this suite pins it: (1) the new skill directory exists
// with the right frontmatter name and no redirect stub of the old directory
// remains, (2) behaviour did not change (`status: trashed`, the `task-trashed`
// log op and `terminal_status: trashed` all stay), (3) the shared/skill docs
// list the new name, and (4) a residue sweep over the live tree finds no
// reference to the old name.
//
// THE RESIDUE REGEX. The retained log op `task-trashed` contains the old skill
// name as a substring, so the sweep matches the old name only when it is NOT
// followed by `ed` (a negative lookahead). The regex and the old-directory name
// are built by concatenation so this file does not need the literal elsewhere;
// the file is additionally excluded from the sweep by path.
//
// SCOPE — repo-local files only. The machine-local ~/.claude/skills/ copy is
// deliberately not inspected.
//
// HERMETIC: read-only walk of the repo. No subprocess, no writes.

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const SKILLS = path.join(REPO, 'lib', 'skills');

const OLD_NAME = 'task' + '-trash';
const RESIDUE = new RegExp(OLD_NAME + '(?!ed)');

// Roots swept for residue (repo-relative, posix separators). Directories are
// walked recursively; files are read directly.
const SWEEP_ROOTS = ['lib', 'test', '.serena/memories', 'wiki', 'README.md', 'CLAUDE.md'];

// Directory names never descended into.
const SKIP_DIRS = new Set(['node_modules', '.git']);

// Paths (repo-relative, posix separators) whose content is a historical record
// of work done under the old name, so rewriting it would falsify history.
// Entries ending in '/' match that directory and everything beneath it.
const HISTORICAL_EXCLUSIONS = [
  'wiki/log.md', // append-only operation log, entries are never edited
  'wiki/hot.md', // generated hot cache, regenerated by wiki-ingest rather than hand-edited
  'wiki/knowledge/sources/', // frozen per-source summaries of immutable raw/ documents
  'wiki/work/roadmaps/', // roadmap records: checklists cite tasks by their original titles
  'wiki/work/tasks/index.md', // active-task index rows quote task titles verbatim
  'wiki/work/uat/index.md', // active-UAT index rows quote UAT titles verbatim, including this rename's own UAT row
  'test/task-close-rename.test.js', // this file: it necessarily spells the old name in its own regex/comments
];

// Frozen work-item records: point-in-time task and UAT files.
const HISTORICAL_PATTERNS = [
  /^wiki\/work\/tasks\/TASK-[^/]*\.md$/,
  /^wiki\/work\/uat\/UAT-[^/]*\.md$/,
  /^wiki\/log-[^/]*\.md$/, // rotated append-only log archives
];

// Path segments marking a terminal-item archive wherever they appear.
const HISTORICAL_SEGMENTS = new Set(['archive']);

function isExcluded(rel) {
  if (rel.split('/').some((s) => HISTORICAL_SEGMENTS.has(s))) return true;
  if (HISTORICAL_PATTERNS.some((re) => re.test(rel))) return true;
  return HISTORICAL_EXCLUSIONS.some((entry) => (entry.endsWith('/') ? rel.startsWith(entry) : rel === entry));
}

function* walk(relPath) {
  const abs = path.join(REPO, ...relPath.split('/'));
  let stat;
  try {
    stat = fs.statSync(abs);
  } catch {
    return;
  }
  if (isExcluded(relPath)) return;
  if (stat.isFile()) {
    yield { abs, rel: relPath };
    return;
  }
  if (!stat.isDirectory()) return;
  for (const ent of fs.readdirSync(abs, { withFileTypes: true })) {
    if (ent.isDirectory() && SKIP_DIRS.has(ent.name)) continue;
    yield* walk(relPath + '/' + ent.name);
  }
}

// Unreadable or binary files (a NUL byte in the buffer) are treated as non-matches.
function readText(abs) {
  try {
    const buf = fs.readFileSync(abs);
    return buf.includes(0) ? null : buf.toString('utf8');
  } catch {
    return null;
  }
}

const readRepo = (...parts) => fs.readFileSync(path.join(REPO, ...parts), 'utf8');

test('lib/skills/task-close/SKILL.md exists with name: task-close', () => {
  const skill = path.join(SKILLS, 'task-close', 'SKILL.md');
  assert.ok(fs.existsSync(skill), 'lib/skills/task-close/SKILL.md must exist');
  const frontmatter = fs.readFileSync(skill, 'utf8').split(/^---\s*$/m)[1] || '';
  assert.match(frontmatter, /^name:\s*task-close\s*$/m, 'frontmatter name must be task-close');
});

test('the old skill directory is gone (no redirect stub)', () => {
  assert.ok(!fs.existsSync(path.join(SKILLS, OLD_NAME)), 'the old skill directory must not exist (hard rename, no stub)');
});

test('task-close keeps its behaviour surface: trashed status, task-trashed log op, uat family', () => {
  const text = readRepo('lib', 'skills', 'task-close', 'SKILL.md');
  assert.ok(text.includes('`terminal_status: trashed`'), 'terminal_status: trashed archive delegation must be retained');
  assert.ok(text.includes('task-trashed'), 'the task-trashed log op must be retained');
  assert.ok(text.includes('`family: uat`'), 'the family: uat archive delegation must be retained');
});

test('_shared/ID-RESOLUTION.md has a task-close row and lib/skills/README.md lists task-close', () => {
  assert.match(readRepo('lib', 'skills', '_shared', 'ID-RESOLUTION.md'), /^\|.*`task-close`/m, 'ID-RESOLUTION.md must have a task-close row');
  assert.match(readRepo('lib', 'skills', 'README.md'), /`task-close`/, 'lib/skills/README.md must list task-close');
});

test('no live file outside the historical exclusions references the old skill name', () => {
  const hits = [];
  for (const root of SWEEP_ROOTS) {
    for (const { abs, rel } of walk(root)) {
      const text = readText(abs);
      if (text === null) continue;
      text.split('\n').forEach((line, i) => {
        if (RESIDUE.test(line)) hits.push(`${rel}:${i + 1}`);
      });
    }
  }
  assert.deepEqual(hits, [], `stale references to the renamed skill:\n  ${hits.join('\n  ')}`);
});


test('task-close header: description leads with "Close", H1 is "# Close Task", roadmap-reference rule retained', () => {
  const text = readRepo('lib', 'skills', 'task-close', 'SKILL.md');
  const frontmatter = text.split(/^---\s*$/m)[1] || '';
  assert.match(frontmatter, /^description:\s*Close\b.*trashed/m, 'description must lead with "Close" and keep the trashed semantics');
  assert.match(frontmatter, /^category:\s*planning\s*$/m, 'category must be unchanged');
  assert.match(frontmatter, /^argument-hint:\s*<path\/to\/task-file\.md>\s*$/m, 'argument-hint must be unchanged');
  assert.match(text, /^# Close Task\s*$/m, 'H1 must be "# Close Task"');
  assert.ok(!/^# Trash Task\s*$/m.test(text), 'the old "# Trash Task" H1 must be gone');
  assert.ok(text.includes('**Do NOT remove references from roadmaps, decisions, or other files**'), 'the roadmap/decision reference-preservation rule must be retained');
});

test('lifecycle docs (local and template) name /task-close for the trashed status', () => {
  const files = [
    ['wiki', 'work', 'tasks', 'lifecycle.md'],
    ['wiki', 'work', 'uat', 'lifecycle.md'],
    ['lib', 'scripts', 'templates', 'wiki', 'work', 'tasks', 'lifecycle.md'],
    ['lib', 'scripts', 'templates', 'wiki', 'work', 'uat', 'lifecycle.md'],
  ];
  for (const parts of files) {
    const text = readRepo(...parts);
    assert.ok(text.includes('/task-close'), `${parts.join('/')} must reference /task-close`);
    assert.ok(/\btrashed\b/.test(text), `${parts.join('/')} must keep the trashed status`);
  }
});

test('CLAUDE.md, wiki-tidy, prd-deprecate and adr-deprecate reference /task-close', () => {
  assert.match(readRepo('CLAUDE.md'), /^\|\s*`\/task-close <path>`/m, 'CLAUDE.md Custom Commands table must list /task-close <path>');
  assert.ok(readRepo('lib', 'skills', 'wiki-tidy', 'SKILL.md').includes('task-close'), 'wiki-tidy must name task-close');
  assert.ok(readRepo('lib', 'skills', 'prd-deprecate', 'SKILL.md').includes('/task-close'), 'prd-deprecate must suggest /task-close');
  assert.ok(readRepo('lib', 'skills', 'adr-deprecate', 'SKILL.md').includes('/task-close'), 'adr-deprecate must suggest /task-close');
});
