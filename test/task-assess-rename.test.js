#!/usr/bin/env node
// Static enforcement of TASK-0110's hard rename of the old audit-named task
// skill to `task-assess`. Zero-dependency: node:test + node:assert only, mirroring the
// sibling skill-content suites (test/archive-work-item.test.js).
//
// Run: npm test   (or: node --test test/task-assess-rename.test.js)
//
// WHY THIS IS TESTED AT ALL. Skills are markdown-as-program: a stale
// reference to the old name in a sibling skill, a doc table, a test constant or a
// knowledge page is a silent runtime failure (an agent is told to invoke a skill
// that no longer exists). The rename therefore cannot be verified by running
// anything — it is enforced by a residue sweep over the live tree, plus a check
// that the new skill directory exists and no redirect stub was left behind
// (ROADMAP-0014 Note 4: old names are hard-renamed, no stubs).
//
// SCOPE — repo-local files only. The machine-local ~/.claude/skills/ copy is
// deliberately not inspected (TASK-0122 prunes stale installed skills).
//
// HERMETIC: read-only walk of the repo. No subprocess, no writes.

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const SKILLS = path.join(REPO, 'lib', 'skills');

// Built by concatenation so this file does not match its own sweep.
const RESIDUE = new RegExp('task' + '[-_ ]' + 'audit', 'i');

// Paths (repo-relative, posix separators) whose content records work done under
// the old name. A directory entry matches itself and everything beneath it; a
// file entry matches that file. Later Phase 4 renames extend this list rather
// than forking the test.
const HISTORICAL_ALLOWLIST = [
  '.git', // VCS internals
  'node_modules', // third-party code
  'raw', // immutable ground-truth sources
  'wiki/log.md', // append-only operation log
  'wiki/hot.md', // regenerated by the hot-cache refresh, never edited by hand
  'wiki/work', // point-in-time task/UAT/roadmap/decision records
  '.serena/cache', // language-server cache, machine-local
  '.docs', // skill scratch/report output
];

// Path segments that mark a terminal-item archive wherever they appear.
const HISTORICAL_SEGMENTS = new Set(['archive']);

const TEXT_EXT = new Set(['.md', '.js', '.sh', '.json', '.yml', '.yaml']);

function isAllowlisted(rel) {
  const segments = rel.split('/');
  if (segments.some((s) => HISTORICAL_SEGMENTS.has(s))) return true;
  if (/^wiki\/log-[^/]*\.md$/.test(rel)) return true; // rotated log archives
  return HISTORICAL_ALLOWLIST.some((entry) => rel === entry || rel.startsWith(entry + '/'));
}

function* walk(dir) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, ent.name);
    const rel = path.relative(REPO, abs).split(path.sep).join('/');
    if (isAllowlisted(rel)) continue;
    if (ent.isDirectory()) yield* walk(abs);
    else if (ent.isFile() && TEXT_EXT.has(path.extname(ent.name))) yield { abs, rel };
  }
}

test('lib/skills/task-assess/SKILL.md exists with name: task-assess', () => {
  const skill = path.join(SKILLS, 'task-assess', 'SKILL.md');
  assert.ok(fs.existsSync(skill), 'lib/skills/task-assess/SKILL.md must exist');
  const frontmatter = fs.readFileSync(skill, 'utf8').split(/^---\s*$/m)[1] || '';
  assert.match(frontmatter, /^name:\s*task-assess\s*$/m, 'frontmatter name must be task-assess');
});

test('the old skill directory is gone (no redirect stub)', () => {
  const stubDir = path.join(SKILLS, 'task' + '-audit');
  assert.ok(!fs.existsSync(stubDir), 'the old skill directory must not exist (hard rename, no stub)');
});

test('no live file outside the historical allowlist references the old skill name', () => {
  const hits = [];
  for (const { abs, rel } of walk(REPO)) {
    fs.readFileSync(abs, 'utf8')
      .split('\n')
      .forEach((line, i) => {
        if (RESIDUE.test(line)) hits.push(`${rel}:${i + 1}`);
      });
  }
  assert.deepEqual(hits, [], `stale references to the renamed skill:\n  ${hits.join('\n  ')}`);
});

const readRepo = (...parts) => fs.readFileSync(path.join(REPO, ...parts), 'utf8');

test('task-assess/SKILL.md description leads with "Assess" and keeps its non-name frontmatter keys', () => {
  const frontmatter = readRepo('lib', 'skills', 'task-assess', 'SKILL.md').split(/^---\s*$/m)[1] || '';
  assert.match(frontmatter, /^description:\s*Assess\b/m, 'description must lead with "Assess"');
  for (const key of ['category', 'model', 'argument-hint', 'disable-model-invocation', 'user-invocable']) {
    assert.match(frontmatter, new RegExp(`^${key}:`, 'm'), `frontmatter must keep ${key}`);
  }
});

test('task-assess/SKILL.md heading, empty-set message, banner and index cross-link use the new name', () => {
  const text = readRepo('lib', 'skills', 'task-assess', 'SKILL.md');
  assert.match(text, /^# Task Assess$/m, 'H1 must be "# Task Assess"');
  assert.ok(text.includes('nothing to assess'), 'empty-set message must say "nothing to assess"');
  assert.ok(text.includes('Auto-generated by `/task-assess` on YYYY-MM-DD'), 'banner must name /task-assess');
  assert.ok(text.includes('regenerated by /task-assess'), 'index cross-link text must name /task-assess');
});

test('task-assess keeps its behaviour surface: --json flag and the dependency-graph.md output file', () => {
  const text = readRepo('lib', 'skills', 'task-assess', 'SKILL.md');
  assert.ok(text.includes('--json'), 'the --json flag must be retained');
  assert.ok(text.includes('dependency-graph.md'), 'the wiki/work/tasks/dependency-graph.md output must be retained');
  assert.ok(text.includes('terminal_status: done'), 'the terminal_status: done archive delegation must be retained');
});

test('CLAUDE.md, lib/skills/README.md and ARCHIVE-WORK-ITEM.md name /task-assess in their skill rows', () => {
  assert.match(readRepo('CLAUDE.md'), /^\| `\/task-assess \[--mermaid\] \[--json\]` \|/m, 'CLAUDE.md Custom Commands row');
  assert.match(readRepo('lib', 'skills', 'README.md'), /^\| `task-assess` \|/m, 'lib/skills/README.md skills table row');
  assert.match(
    readRepo('lib', 'skills', '_shared', 'ARCHIVE-WORK-ITEM.md'),
    /^\| `task-assess` \| `tasks` \| `done` \|/m,
    'ARCHIVE-WORK-ITEM.md consumer row'
  );
});

test('wiki-work-family-cross-linking-gaps.md tags carry task-assess', () => {
  const frontmatter =
    readRepo('wiki', 'knowledge', 'concepts', 'wiki-work-family-cross-linking-gaps.md').split(/^---\s*$/m)[1] || '';
  assert.match(frontmatter, /^tags:.*\btask-assess\b/m, 'tags: must include task-assess');
});
