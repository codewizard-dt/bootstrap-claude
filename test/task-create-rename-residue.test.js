#!/usr/bin/env node
// Static enforcement of the hard rename of the old add-named task skill to
// `task-create` (TASK-0112). Zero-dependency: node:test + node:assert only,
// mirroring the sibling rename suites (test/task-close-rename.test.js,
// test/task-assess-rename.test.js).
//
// Run: npm test   (or: node --test test/task-create-rename-residue.test.js)
//
// WHY THIS IS TESTED AT ALL. Skills are markdown-as-program: a stale reference
// to the old skill name in a sibling skill, a doc table, a test constant or a
// knowledge page is a silent runtime failure (an agent is told to invoke a
// skill that no longer exists). The rename cannot be verified by running
// anything, so this suite pins it: (1) the old skill directory is gone (no
// redirect stub) and the new one exists with the right frontmatter name,
// (2) a repo-wide residue sweep finds no reference to the old name, and
// (3) lib/skills/README.md lists the new name and not the old one.
//
// THE TOKEN. The old name is built from fragments so this file never contains
// the literal; the file is additionally skipped from the sweep by path.
//
// HISTORICAL ALLOWLIST. The sweep walks the whole repo root but deliberately
// skips locations that are immutable or point-in-time records of work done
// under the old name, where rewriting would falsify history:
//   .git/, node_modules/            VCS internals and vendored dependencies
//   raw/                            immutable ground-truth sources (CLAUDE.md rule 1)
//   .docs/                          legacy/skill scratch reports, not maintained docs
//   .serena/cache/                  generated language-server symbol cache
//   wiki/log.md, wiki/log-*.md      append-only operation log (entries never edited)
//   wiki/hot.md                     generated hot cache, regenerated by wiki-ingest
//   wiki/knowledge/sources/         frozen per-source summaries of immutable raw/ docs
//   any archive/ directory          terminal work items, frozen on archival
//   wiki/work/*/index.md            family indexes quote item titles verbatim
//   TASK-*, UAT-*, BUG-*,           point-in-time work-item records that cite the
//   ROADMAP-*, DEC-* basenames      old name in their original titles and bodies
//   test/task-create-rename-residue.test.js   this file
// Everything else (lib/, test/, bin/, wiki/knowledge/concepts|entities,
// lifecycle docs, CLAUDE.md, README.md, .serena/memories, ...) is live and must
// be clean.
//
// SCOPE - repo-local files only. The machine-local ~/.claude/skills/ copy is
// deliberately not inspected.
//
// HERMETIC: read-only walk of the repo. No subprocess, no writes.

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const SKILLS = path.join(REPO, 'lib', 'skills');

const OLD_NAME = 'task' + '-add';
const SELF = 'test/task-create-rename-residue.test.js';

// Directory names never descended into, at any depth.
const SKIP_DIR_NAMES = new Set(['.git', 'node_modules', 'archive']);

// Repo-relative directory prefixes (posix separators) never descended into.
const SKIP_DIR_PREFIXES = ['raw', '.docs', '.serena/cache', 'wiki/knowledge/sources'];

// Repo-relative files (posix separators) skipped.
const SKIP_FILES = new Set(['wiki/log.md', 'wiki/hot.md', SELF]);

// Pattern-matched skips: rotated log archives, family indexes, and frozen
// work-item records identified by basename prefix.
const SKIP_PATTERNS = [/^wiki\/log-[^/]*\.md$/, /^wiki\/work\/[^/]+\/index\.md$/];
const SKIP_BASENAME = /^(TASK|UAT|BUG|ROADMAP|DEC|ADR)-/;

function isSkippedDir(rel, name) {
  if (SKIP_DIR_NAMES.has(name)) return true;
  return SKIP_DIR_PREFIXES.some((p) => rel === p);
}

function isSkippedFile(rel) {
  if (SKIP_FILES.has(rel)) return true;
  if (SKIP_PATTERNS.some((re) => re.test(rel))) return true;
  return SKIP_BASENAME.test(path.posix.basename(rel));
}

function* walk(rel) {
  const abs = rel === '' ? REPO : path.join(REPO, ...rel.split('/'));
  let entries;
  try {
    entries = fs.readdirSync(abs, { withFileTypes: true });
  } catch {
    return;
  }
  for (const ent of entries) {
    const childRel = rel === '' ? ent.name : rel + '/' + ent.name;
    if (ent.isDirectory()) {
      if (isSkippedDir(childRel, ent.name)) continue;
      yield* walk(childRel);
    } else if (ent.isFile()) {
      if (isSkippedFile(childRel)) continue;
      yield { abs: path.join(abs, ent.name), rel: childRel };
    }
  }
}

// Unreadable or binary files (a NUL byte in the buffer) are treated as skipped.
function readText(abs) {
  try {
    const buf = fs.readFileSync(abs);
    return buf.includes(0) ? null : buf.toString('utf8');
  } catch {
    return null;
  }
}

test('old skill directory is gone; lib/skills/task-create/SKILL.md exists with name: task-create', () => {
  assert.ok(!fs.existsSync(path.join(SKILLS, OLD_NAME)), 'the old skill directory must not exist (hard rename, no stub)');
  const skill = path.join(SKILLS, 'task-create', 'SKILL.md');
  assert.ok(fs.existsSync(skill), 'lib/skills/task-create/SKILL.md must exist');
  const frontmatter = fs.readFileSync(skill, 'utf8').split(/^---\s*$/m)[1] || '';
  assert.match(frontmatter, /^name:\s*task-create\s*$/m, 'frontmatter name must be task-create');
});

test('residue sweep: no live file in the repo references the old skill name', () => {
  const hits = [];
  for (const { abs, rel } of walk('')) {
    const text = readText(abs);
    if (text === null) continue;
    text.split('\n').forEach((line, i) => {
      if (line.includes(OLD_NAME)) hits.push(`${rel}:${i + 1}`);
    });
  }
  assert.deepEqual(hits, [], `stale references to the renamed skill:\n  ${hits.join('\n  ')}`);
});

test('lib/skills/README.md lists task-create and does not list the old name', () => {
  const text = fs.readFileSync(path.join(SKILLS, 'README.md'), 'utf8');
  assert.ok(text.includes('`task-create`'), 'lib/skills/README.md must list task-create');
  assert.ok(!text.includes(OLD_NAME), 'lib/skills/README.md must not mention the old skill name');
});
